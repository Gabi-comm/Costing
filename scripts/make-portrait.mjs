// Samples a photo into the dot grid used by components/DotPortrait.tsx.
// Usage: node scripts/make-portrait.mjs <image> [cols] [--preview out.png]
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const [src, colsArg, flag, previewOut] = process.argv.slice(2);
if (!src) throw new Error("usage: node scripts/make-portrait.mjs <image> [cols] [--preview out.png]");
const COLS = Number(colsArg) || 96;

const meta = await sharp(src).metadata();
const ROWS = Math.round(COLS * (meta.height / meta.width));
// Local contrast first so the face isn't drowned out by the white shirt.
const equalized = await sharp(src).removeAlpha().clahe({ width: 160, height: 160, maxSlope: 4 }).toBuffer();
const { data } = await sharp(equalized).resize(COLS, ROWS, { fit: "fill" }).raw().toBuffer({ resolveWithObject: true });
const { data: color } = await sharp(src).resize(COLS, ROWS, { fit: "fill" }).removeAlpha().raw().toBuffer({ resolveWithObject: true });

// Background is ~0.24 luminance; lift the subject above it and let darks fall away.
const LOW = Number(process.env.LOW ?? 0.3), HIGH = Number(process.env.HIGH ?? 0.85), GAMMA = Number(process.env.GAMMA ?? 0.8);
let levels = "", warm = "";
for (let i = 0; i < COLS * ROWS; i++) {
  const [r, g, b] = [data[i * 3] / 255, data[i * 3 + 1] / 255, data[i * 3 + 2] / 255];
  const l = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  const v = Math.pow(Math.min(1, Math.max(0, (l - LOW) / (HIGH - LOW))), GAMMA);
  levels += Math.round(v * 15).toString(16);
  // Strongly saturated orange (the glasses) gets a warm dot; skin is less saturated.
  const [cr, cg, cb] = [color[i * 3], color[i * 3 + 1], color[i * 3 + 2]];
  const sat = (Math.max(cr, cg, cb) - Math.min(cr, cg, cb)) / Math.max(1, Math.max(cr, cg, cb));
  warm += sat > 0.72 && cr > 90 && cr > cg && cg > cb && v > 0.05 ? "1" : "0";
}

const out = `// Generated by scripts/make-portrait.mjs — do not edit by hand.
export const PORTRAIT = {
  cols: ${COLS},
  rows: ${ROWS},
  /** One hex digit (0–f) of brightness per dot, row by row. */
  levels: "${levels}",
  /** "1" where the dot takes the warm accent color. */
  warm: "${warm}",
};
`;
writeFileSync(new URL("../lib/portrait-data.ts", import.meta.url), out);
console.log(`wrote lib/portrait-data.ts (${COLS}x${ROWS})`);

if (flag === "--preview" && previewOut) {
  const cell = 8, W = COLS * cell, H = ROWS * cell;
  let circles = "";
  for (let y = 0; y < ROWS; y++)
    for (let x = 0; x < COLS; x++) {
      const i = y * COLS + x, v = parseInt(levels[i], 16) / 15;
      if (v < 0.05) continue;
      circles += `<circle cx="${(x + 0.5) * cell}" cy="${(y + 0.5) * cell}" r="${(v * cell * 0.5).toFixed(2)}" fill="${warm[i] === "1" ? "#F4B183" : "#CADCEA"}"/>`;
    }
  await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}"><rect width="100%" height="100%" fill="#091525"/>${circles}</svg>`)).png().toFile(previewOut);
  console.log("preview", previewOut);
}
